// Generates one HTML page per section / project / film (EN + FR) from /index.html,
// each with its own title, description, canonical, hreflang, Open Graph and JSON-LD,
// plus sitemap.xml with images and videos.
// Run from the repo root:  node tools/build-pages.mjs
// Edit only /index.html (site + data). Every other page is generated — never edit them by hand.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const SITE = 'https://juliavaskul.com';
const ROOT = process.cwd();
const SRC = path.join(ROOT, 'index.html');
const MARK_A = '<!--SEO-->', MARK_B = '<!--/SEO-->';
const GEN_NOTE = '<!-- GENERATED by tools/build-pages.mjs from /index.html — do not edit this file -->\n';

let html = fs.readFileSync(SRC, 'utf8');
if (!html.includes(MARK_A) || !html.includes(MARK_B)) throw new Error('SEO markers missing in index.html');

// ---------- pull the data out of the site script ----------
const grab = (start, end) => {
  const i = html.indexOf(start); if (i < 0) throw new Error('not found: ' + start);
  const j = html.indexOf(end, i); if (j < 0) throw new Error('end not found: ' + end);
  return html.slice(i + start.length, j);
};
const ev = code => vm.runInNewContext('(' + code + ')');
const S = ev('[' + grab('const S=[', '].map(a=>({s:a[0],t:a[1]') + ']').map(a => ({ s: a[0], t: a[1], b: a[2], c: a[3], fr: a[4], cov: a[5], d: a[6], idea_en: a[7], desc_en: a[8] }));
const FRTXT = ev(grab('const FRTXT=', ';\n'));
const F = ev('[' + grab('const F=[', ".map(a=>({s:a[0],t:a[1],b:a[2],c:'film'").replace(/\]\s*$/, '') + ']').map(a => ({ s: a[0], t: a[1], b: a[2], c: 'film', ar: a[3], desc_en: a[4] }));
const FILMFR = ev(grab('const FILMFR=', ';\n'));
const FASH = ev(grab('const FASH=', ';'));
const BEAU = ev(grab('const BEAU=', ';'));
const ALT = ev(grab('const ALT=', ';\nconst altFor'));
S.forEach(x => { const f = FRTXT[x.s] || []; x.idea_fr = f[0] || x.idea_en; x.desc_fr = f[1] || x.desc_en; });
F.forEach(f => { f.desc_fr = FILMFR[f.s] || ''; });
const BY = Object.fromEntries([...S, ...F].map(x => [x.s, x]));

const datesFile = path.join(ROOT, 'tools', 'video-dates.json');
const VDATES = fs.existsSync(datesFile) ? JSON.parse(fs.readFileSync(datesFile, 'utf8')) : {};
const today = new Date().toISOString().slice(0, 10);
let datesChanged = false;
F.forEach(f => { if (!VDATES[f.s]) { VDATES[f.s] = today; datesChanged = true; } });

// ---------- helpers ----------
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const clip = (s, n = 158) => { s = String(s).replace(/\s+/g, ' ').trim(); if (s.length <= n) return s; const c = s.slice(0, n - 1); return c.slice(0, c.lastIndexOf(' ')).replace(/[,;:—–-]\s*$/, '') + '…'; };
const isOrig = x => x.b === 'Original design';
const alt = (k, l) => (ALT[k] || [])[l === 'fr' ? 1 : 0] || '';
const imgUrl = (s, n) => `${SITE}/m/img/${s}-${n}.jpg`;
const pathFor = (key, l) => {
  const pre = l === 'fr' ? '/fr' : '';
  if (key === 'about') return pre + '/';
  if (['fashion', 'beauty', 'film', 'contact', 'legal'].includes(key)) return `${pre}/${key}/`;
  const x = BY[key]; return `${pre}/${x.c}/${x.s}/`;
};
const url = (key, l) => SITE + pathFor(key, l);
const PERSON = { '@type': 'Person', name: 'Julia Vaskul', url: SITE + '/' };

const L = {
  en: {
    home: ['Julia Vaskul — AI Creative Director · Fashion & Beauty', 'Julia Vaskul, AI creative director based in Hendaye, France. Fully AI-generated fashion and beauty campaigns and films, held to the standards of a real shoot.'],
    fashion: ['Fashion — AI fashion campaigns & editorials | Julia Vaskul', list => `AI-generated fashion campaigns and editorials by Julia Vaskul: ${list}.`],
    beauty: ['Beauty — AI beauty & skincare campaigns | Julia Vaskul', list => `AI-generated beauty and skincare campaigns by Julia Vaskul: ${list}.`],
    film: ['Film — AI fashion & luxury films | Julia Vaskul', list => `AI-generated fashion, beauty and luxury films directed by Julia Vaskul: ${list}.`],
    contact: ['Contact — Julia Vaskul, AI creative director', 'Tell Julia Vaskul about your brand and project: AI-generated images and films for fashion, beauty and luxury campaigns.'],
    legal: ['Legal notice — Julia Vaskul', 'Legal notice and personal data information for juliavaskul.com.'],
    proj: x => isOrig(x) ? `${x.t} — AI ${x.c} editorial | Julia Vaskul` : `${x.t} — ${x.b} concept campaign (AI) | Julia Vaskul`,
    film1: f => `${f.t} — ${f.b} concept film (AI) | Julia Vaskul`,
    filmDesc: f => f.desc_en || `An AI-generated concept film inspired by ${f.b}, directed by Julia Vaskul.`,
    og: 'en_GB',
  },
  fr: {
    home: ['Julia Vaskul — Directrice de création IA · Mode & Beauté', 'Julia Vaskul, directrice de création IA basée à Hendaye, France. Campagnes et films mode et beauté entièrement générés par IA, aux standards d’un vrai shooting.'],
    fashion: ['Mode — campagnes et éditoriaux mode IA | Julia Vaskul', list => `Campagnes et éditoriaux mode générés par IA, par Julia Vaskul : ${list}.`],
    beauty: ['Beauté — campagnes beauté et soin IA | Julia Vaskul', list => `Campagnes beauté et soin générées par IA, par Julia Vaskul : ${list}.`],
    film: ['Film — films mode et luxe IA | Julia Vaskul', list => `Films mode, beauté et luxe générés par IA, réalisés par Julia Vaskul : ${list}.`],
    contact: ['Contact — Julia Vaskul, directrice de création IA', 'Parlez à Julia Vaskul de votre marque et de votre projet : images et films générés par IA pour la mode, la beauté et le luxe.'],
    legal: ['Mentions légales — Julia Vaskul', 'Mentions légales et données personnelles de juliavaskul.com.'],
    proj: x => isOrig(x) ? `${x.t} — éditorial ${x.c === 'fashion' ? 'mode' : 'beauté'} IA | Julia Vaskul` : `${x.t} — campagne concept ${x.b} (IA) | Julia Vaskul`,
    film1: f => `${f.t} — film concept ${f.b} (IA) | Julia Vaskul`,
    filmDesc: f => f.desc_fr || `Film concept généré par IA, inspiré de ${f.b}, réalisé par Julia Vaskul.`,
    og: 'fr_FR',
  },
};
const listOf = keys => keys.map(k => { const x = BY[k]; return isOrig(x) ? x.t : `${x.t} (${x.b})`; }).join(', ');

// ---------- page definitions ----------
function page(key, l) {
  const T = L[l];
  let title, desc, image = SITE + '/og.jpg?v=2', imageAlt = 'Julia Vaskul — AI Creative Director', ld = null, robots = null, ogType = 'website';
  if (key === 'about') { [title, desc] = T.home; }
  else if (key === 'fashion' || key === 'beauty') {
    const keys = key === 'fashion' ? FASH : BEAU; title = T[key][0]; desc = clip(T[key][1](listOf(keys)));
    const c = BY[keys[0]]; image = imgUrl(c.s, c.fr[0]); imageAlt = alt(`${c.s}-${c.fr[0]}`, l);
    ld = { '@context': 'https://schema.org', '@type': 'CollectionPage', name: title, url: url(key, l), inLanguage: l, author: PERSON,
      hasPart: keys.map(k => ({ '@type': 'CreativeWork', name: BY[k].t, url: url(k, l) })) };
  } else if (key === 'film') {
    title = T.film[0]; desc = clip(T.film[1](F.map(f => `${f.t} (${f.b})`).join(', ')));
    image = `${SITE}/m/cov/${F[0].s}.jpg`; imageAlt = alt(F[0].s, l);
    ld = { '@context': 'https://schema.org', '@type': 'CollectionPage', name: title, url: url(key, l), inLanguage: l, author: PERSON,
      hasPart: F.map(f => ({ '@type': 'VideoObject', name: f.t, url: url(f.s, l) })) };
  } else if (key === 'contact' || key === 'legal') {
    [title, desc] = T[key]; if (key === 'legal') robots = 'noindex, follow';
  } else {
    const x = BY[key];
    if (x.c === 'film') {
      title = T.film1(x); desc = clip(T.filmDesc(x)); image = `${SITE}/m/cov/${x.s}.jpg`; imageAlt = alt(x.s, l); ogType = 'video.other';
      ld = { '@context': 'https://schema.org', '@type': 'VideoObject', name: `${x.t} — ${x.b}`, description: T.filmDesc(x),
        thumbnailUrl: [image], uploadDate: VDATES[x.s], contentUrl: `${SITE}/m/vid/${x.s}.mp4`, url: url(key, l), inLanguage: l, creator: PERSON };
    } else {
      const idea = x['idea_' + l], d = x['desc_' + l];
      title = T.proj(x); desc = clip(`${idea} ${d}`); image = imgUrl(x.s, x.fr[0]); imageAlt = alt(`${x.s}-${x.fr[0]}`, l); ogType = 'article';
      ld = { '@context': 'https://schema.org', '@type': 'CreativeWork', name: x.t, headline: title.replace(/ \| Julia Vaskul$/, ''), description: `${idea} ${d}`,
        url: url(key, l), inLanguage: l, creator: PERSON, genre: x.c === 'fashion' ? 'Fashion photography (AI-generated)' : 'Beauty photography (AI-generated)',
        image: x.fr.map(n => ({ '@type': 'ImageObject', contentUrl: imgUrl(x.s, n), caption: alt(`${x.s}-${n}`, l) })) };
    }
  }
  const tags = [
    `<title>${esc(title)}</title>`,
    `<meta name="description" content="${esc(desc)}">`,
    robots ? `<meta name="robots" content="${robots}">` : '',
    `<link rel="canonical" href="${url(key, l)}">`,
    `<link rel="alternate" hreflang="en" href="${url(key, 'en')}">`,
    `<link rel="alternate" hreflang="fr" href="${url(key, 'fr')}">`,
    `<link rel="alternate" hreflang="x-default" href="${url(key, 'en')}">`,
    `<meta property="og:type" content="${ogType}">`,
    `<meta property="og:site_name" content="Julia Vaskul">`,
    `<meta property="og:locale" content="${T.og}">`,
    `<meta property="og:title" content="${esc(title.replace(/ \| Julia Vaskul$/, ''))}">`,
    `<meta property="og:description" content="${esc(desc)}">`,
    `<meta property="og:image" content="${image}">`,
    `<meta property="og:image:alt" content="${esc(imageAlt)}">`,
    `<meta property="og:url" content="${url(key, l)}">`,
    `<meta name="twitter:card" content="summary_large_image">`,
    ld ? `<script type="application/ld+json">${JSON.stringify(ld).replace(/</g, '\\u003c')}</script>` : '',
  ].filter(Boolean).join('\n');
  return { tags, lang: l };
}

function render(key, l) {
  const { tags } = page(key, l);
  const a = html.indexOf(MARK_A), b = html.indexOf(MARK_B);
  let out = html.slice(0, a + MARK_A.length) + '\n' + tags + '\n' + html.slice(b);
  out = out.replace(/<html lang="[a-z]+"/, `<html lang="${l}"`);
  return out;
}

const KEYS = ['about', 'fashion', 'beauty', 'film', 'contact', 'legal', ...FASH, ...BEAU, ...F.map(f => f.s)];
let written = 0;
for (const l of ['en', 'fr']) for (const key of KEYS) {
  const p = pathFor(key, l);
  const file = path.join(ROOT, p, 'index.html');
  let out = render(key, l);
  if (p !== '/') out = out.replace('<!doctype html>', '<!doctype html>\n' + GEN_NOTE.trim());
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== out) { fs.writeFileSync(file, out); written++; }
}
html = fs.readFileSync(SRC, 'utf8');

// ---------- sitemap ----------
const xmlEsc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
let sm = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1" xmlns:video="http://www.google.com/schemas/sitemap-video/1.1">\n';
for (const key of KEYS.filter(k => k !== 'legal')) for (const l of ['en', 'fr']) {
  sm += `<url><loc>${url(key, l)}</loc>`;
  sm += `<xhtml:link rel="alternate" hreflang="en" href="${url(key, 'en')}"/><xhtml:link rel="alternate" hreflang="fr" href="${url(key, 'fr')}"/><xhtml:link rel="alternate" hreflang="x-default" href="${url(key, 'en')}"/>`;
  const x = BY[key];
  if (key === 'about') sm += `<image:image><image:loc>${SITE}/m/img/julia.jpg</image:loc></image:image>`;
  if (x && x.c !== 'film') {
    for (const n of x.fr) sm += `<image:image><image:loc>${imgUrl(x.s, n)}</image:loc></image:image>`;
    for (const k of [1, 2]) sm += `<image:image><image:loc>${SITE}/m/dip/${x.d}_diptych-${k}.jpg</image:loc></image:image>`;
  }
  if (x && x.c === 'film') {
    const T = L[l];
    sm += `<video:video><video:thumbnail_loc>${SITE}/m/cov/${x.s}.jpg</video:thumbnail_loc><video:title>${xmlEsc(`${x.t} — ${x.b}`)}</video:title><video:description>${xmlEsc(T.filmDesc(x))}</video:description><video:content_loc>${SITE}/m/vid/${x.s}.mp4</video:content_loc><video:publication_date>${VDATES[x.s]}</video:publication_date></video:video>`;
  }
  sm += '</url>\n';
}
sm += '</urlset>\n';
const smFile = path.join(ROOT, 'sitemap.xml');
if (!fs.existsSync(smFile) || fs.readFileSync(smFile, 'utf8') !== sm) { fs.writeFileSync(smFile, sm); written++; }
if (datesChanged) fs.writeFileSync(datesFile, JSON.stringify(VDATES, null, 0) + '\n');
console.log(`pages: ${KEYS.length * 2}, files changed: ${written}`);
